"""
gen_corpus.py — build the DeepSeek distillation corpus for the GD32 nano-LM.

Pipeline role (ADR-1: PC/5090 trains, MCU only runs the text artifact):
  Enumerate realistic furnace/sentinel STATES (12 categorical slots) ->
  describe each in Chinese -> ask DeepSeek (a large teacher model family)
  for a ONE-SENTENCE diagnosis+action -> save (slots, sentence) pairs.

The 12-slot schema here is the CONTRACT shared with the firmware: the C side
emits the same control-token IDs from the live sentinel snapshot, so the on-chip
nano-LM sees exactly the distribution it was distilled on. Keep SLOTS in sync
with ai_nanolm build_context() (exported as named constants in nanolm_vocab.h).

Honesty: every sentence is generated by DeepSeek (knowledge distillation), not
hand-written templates. States are physically plausible (fault<->stage<->gas
correlations encoded below), so the teacher never sees nonsense inputs.

Run (on the 5090):
  python3 gen_corpus.py --n 3600 --workers 24 --out corpus.jsonl
  python3 gen_corpus.py --smoke            # 6 calls, print samples, no file
"""
