TEMP_NUM = {"rt": 25, "t200": 215, "t400": 430, "t600": 615, "t800": 820, "t900": 905,
            "t1000": 1010, "t1200": 1215, "t1400": 1415, "t1500": 1500, "over": 1560}


def base_state(stage, host):
    return {"stage": stage, "temp": STAGE_TEMP[stage], "risk": "good", "ramp": "ok",
            "drift": "ok", "tc": "ok", "gas": "ok", "ae": "ok", "vib": "ok",
            "energy": "ok", "host": host, "elem": "ok"}


# scenario -> (slot overrides, risk) ; applied on top of base_state
def scenarios(stage):
    """Physically plausible fault scenarios for a given stage."""
    sc = {"normal": ({}, "good")}
    if stage in ("ramp", "preheat"):
        sc["ramp_fast"] = ({"ramp": "fast", "ae": "anom"}, "bad")
        sc["ramp_slow"] = ({"ramp": "slow", "energy": "high"}, "warn")
    if stage in ("calcine", "sinter", "ramp"):
        sc["drift"] = ({"drift": "hi", "ae": "anom"}, "bad")
        sc["tc_open"] = ({"tc": "open", "temp": "rt"}, "crit")     # open TC reads cold
        sc["tc_short"] = ({"tc": "short", "temp": "over"}, "crit")  # short can read hot/erratic
        sc["elem_alarm"] = ({"elem": "alarm", "ramp": "slow", "energy": "high"}, "bad")
    if stage == "sinter":
        sc["gas_cr6"] = ({"gas": "cr6"}, "bad")          # Cr3+ -> Cr6+ oxidation > 900C
        sc["overtemp"] = ({"temp": "over", "drift": "hi"}, "crit")
    if stage == "calcine":
        sc["gas_co2"] = ({"gas": "co2"}, "warn")          # carbonate decomposition
    if stage in ("preheat", "calcine"):
        sc["gas_hf"] = ({"gas": "hf"}, "bad")             # NH4F / fluoride off-gas
        sc["moist"] = ({"gas": "moist", "drift": "hi"}, "warn")
    if stage in ("calcine", "sinter"):
        sc["vib_abn"] = ({"vib": "abn"}, "warn")          # grinding/transport vibration
    if stage in ("calcine", "sinter", "cool"):
        sc["elem_warn"] = ({"elem": "warn", "energy": "high"}, "warn")
    # a couple of compound faults
    if stage == "sinter":
        sc["cr6_drift"] = ({"gas": "cr6", "drift": "hi", "ae": "anom"}, "crit")
    return sc


def make_state(rng, stage, scen_name, scen):
    overrides, risk = scen
    host = rng.choice(list(SLOTS["host"].keys()))
    st = base_state(stage, host)
    st.update(overrides)
    st["risk"] = risk
    return st


def describe(st):
    """Human-readable Chinese description fed to DeepSeek."""
    parts = []
    parts.append(f"烧结阶段:{SLOTS['stage'][st['stage']][1]}")
    tnum = TEMP_NUM[st["temp"]]
    parts.append(f"炉温:约{tnum}°C")
    parts.append(f"综合风险:{SLOTS['risk'][st['risk']][1]}")
    parts.append(f"升温速率:{SLOTS['ramp'][st['ramp']][1]}")
    parts.append(f"温度漂移:{SLOTS['drift'][st['drift']][1]}")
    parts.append(f"热电偶:{SLOTS['tc'][st['tc']][1]}")
    parts.append(f"气氛:{SLOTS['gas'][st['gas']][1]}")
    parts.append(f"烧结曲线监测:{SLOTS['ae'][st['ae']][1]}")
    parts.append(f"振动:{SLOTS['vib'][st['vib']][1]}")
    parts.append(f"能耗:{SLOTS['energy'][st['energy']][1]}")
    parts.append(f"配方:{SLOTS['host'][st['host']][1]}")
    parts.append(f"加热元件:{SLOTS['elem'][st['elem']][1]}")
    return ";".join(parts) + "。"


def call_deepseek(desc, temperature=0.4, retries=4):
    if not DEEPSEEK_KEY:
        raise RuntimeError("DEEPSEEK_API_KEY is required; never hard-code it")
    body = json.dumps({
        "model": MODEL,
        "messages": [{"role": "system", "content": SYS_PROMPT},
                     {"role": "user", "content": "炉况状态:" + desc + "\n请给出一句话诊断与建议。"}],
        "temperature": temperature, "max_tokens": 80, "stream": False,
    }).encode("utf-8")
    for i in range(retries):
        try:
            req = urllib.request.Request(DEEPSEEK_URL, data=body, headers={
                "Content-Type": "application/json",
                "Authorization": f"Bearer {DEEPSEEK_KEY}"})
            with urllib.request.urlopen(req, timeout=60) as r:
                d = json.loads(r.read().decode("utf-8"))
            txt = d["choices"][0]["message"]["content"].strip()
            txt = txt.replace("\n", "").replace("\r", "").strip().strip('"“”')
            return txt
        except Exception as ex:
            if i == retries - 1:
                return f"__ERR__{ex}"
            time.sleep(1.5 * (i + 1))


def build_states(n, seed=20260603):
    rng = random.Random(seed)
    stages = list(SLOTS["stage"].keys())
    states = []
    # coverage pass: every (stage, scenario) a few times
    for stage in stages:
        for scen_name, scen in scenarios(stage).items():
            reps = 8 if scen_name == "normal" else 6
            for _ in range(reps):
                states.append(make_state(rng, stage, scen_name, scen))
    # fill remainder with random (stage, scenario) draws
    while len(states) < n:
        stage = rng.choice(stages)
        scs = scenarios(stage)
        scen_name = rng.choice(list(scs.keys()))
        states.append(make_state(rng, stage, scen_name, scs[scen_name]))
    rng.shuffle(states)
    return states[:n]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=3600)
    ap.add_argument("--workers", type=int, default=24)
    ap.add_argument("--out", default="corpus.jsonl")
    ap.add_argument("--smoke", action="store_true")
    args = ap.parse_args()

    if args.smoke:
        rng = random.Random(1)
        demo = []
        for stage in ["sinter", "calcine", "ramp", "sinter", "idle", "cool"]:
            scs = scenarios(stage)
            name = rng.choice(list(scs.keys()))
            demo.append(make_state(rng, stage, name, scs[name]))
        for st in demo:
            desc = describe(st)
            out = call_deepseek(desc)
            print("STATE:", {k: st[k] for k in SLOT_ORDER})
            print("DESC :", desc)
            print("DIAG :", out)
            print("-" * 70)
        return

    states = build_states(args.n)
    print(f"built {len(states)} states; querying DeepSeek with {args.workers} workers...")
    t0 = time.time()
    rows = [None] * len(states)
    done = 0
    with ThreadPoolExecutor(max_workers=args.workers) as ex:
        futs = {ex.submit(call_deepseek, describe(st)): i for i, st in enumerate(states)}
        for fut in as_completed(futs):
            i = futs[fut]
            txt = fut.result()
            rows[i] = (states[i], txt)
            done += 1
            if done % 200 == 0:
                print(f"  {done}/{len(states)}  ({time.time()-t0:.0f}s)")

    n_err = 0
    n_ok = 0
    with open(args.out, "w", encoding="utf-8") as f:
        for st, txt in rows:
            if txt.startswith("__ERR__") or not txt or len(txt) > 60:
                n_err += 1
                continue
            f.write(json.dumps({"slots": st, "text": txt}, ensure_ascii=False) + "\n")
            n_ok += 1
    print(f"done: {n_ok} ok, {n_err} dropped -> {args.out}  ({time.time()-t0:.0f}s)")


if __name__ == "__main__":
    main()
