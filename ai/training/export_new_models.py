"""
export_new_models.py — emit float-C headers for AI-6/7/8/9/10 (CIMC Lab-Sentinel)
=================================================================================
Loads the 4 trained MLPs (.pt) + builds the AI-9 retrieval DB, and emits
hand-written-float-C weight headers into firmware/ai_models_c/, plus host golden
headers into model/host_test/. Mirrors the export style of AI-4/AI-5.

Design choice (keeps the MCU side as pure matrix ops, no formula parser):
  AI-6/7 take a 24-D formula descriptor; AI-9 a 18-D recipe vector. Those are
  PRECOMPUTED on PC for a small set of recipe PRESETS and shipped in
  recipe_presets.h. The on-device engine just runs the MLP / kNN on the preset's
  vector (selected by recipe index). AI-8 computes its 5 features from the recipe
  temps/hours directly (already on-device). AI-10 computes 8 features from a live
  vibration window on-device.

Run:  cd CIMC/model && python export_new_models.py
"""

